// ---------------- Networking ----------------
function serverOrigin() {
  // `SF_SERVER_URL` (set in config.js, generated by build-web.js) overrides the
  // page origin, e.g. when running inside a Capacitor app (local file origin).
  return window.SF_SERVER_URL || location.origin;
}
function wsUrl() {
  return serverOrigin().replace(/^http/, 'ws') + '/';
}
function connect(url) {
  return new Promise((resolve, reject) => {
    const ws = new WebSocket(url);
    ws.onopen = () => resolve(ws);
    ws.onerror = () => reject(new Error('Connection failed'));
  });
}
function wsSend(obj) {
  if (App.ws && App.ws.readyState === WebSocket.OPEN) App.ws.send(JSON.stringify(obj));
}

async function ensureWs() {
  if (App.ws && App.ws.readyState === WebSocket.OPEN) return true;
  try {
    App.ws = await connect(wsUrl());
    App.ws.onmessage = (ev) => onMessage(JSON.parse(ev.data));
    return true;
  } catch (err) {
    $('home-error').textContent = 'Cannot reach server. Start it (`npm start`) or use Play vs AI.';
    return false;
  }
}

function onMessage(msg) {
  switch (msg.type) {
    case 'joined':
      App.room = msg.room;
      App.player = msg.player;
      App.players = msg.players;
      App.you = msg.you;
      App.phase = msg.phase;
      renderLobby();
      showScreen('lobby');
      break;
    case 'error':
      $('home-error').textContent = msg.error;
      break;
    case 'plan_ack':
      App.submitted = true;
      updateControls();
      break;
    case 'state':
      applyStateMsg(msg);
      break;
  }
}

function applyStateMsg(msg) {
  App.phase = msg.phase;
  App.tick = msg.tick;
  App.round = msg.round;
  App.timerEnds = msg.timerMs ? Date.now() + msg.timerMs : 0;
  App.state = msg.state;
  App.you = msg.you;
  if (App.screen !== 'game') showScreen('game');

  if (msg.phase === 'plan') {
    App.submitted = false;
    App.moves = {};
    App.pass = { type: 'keep' };
    App.passMode = false;
    if (msg.lastGoal) toast(`Goal for ${msg.lastGoal}! ${msg.state.score.A}-${msg.state.score.B}`);
  }
  if (msg.winner) toast(winnerText(msg.winner, msg.you));
  renderGame();
}

function winnerText(team, you) {
  return team === you ? 'You WIN! 🏆' : `${team} team wins!`;
}

